function orderLine(
  productId: string,
  qty: number,
  options: Partial<
    Pick<OrderLineSnapshot, 'partClass' | 'source' | 'sellable' | 'quoteRequired'> & {
      unitPriceCents: number;
      zhName: string;
      enName: string;
    }
  > = {},
): OrderLineSnapshot {
  const product = getProductById(productId);
  if (!product) throw new Error(`Unknown product id: ${productId}`);

  const partClass = options.partClass ?? product.partClass;
  const quoteRequired =
    options.quoteRequired ?? (partClass !== 'standard' || product.priceCents <= 0);
  const sellable = options.sellable ?? !quoteRequired;
  const unitPriceCents = options.unitPriceCents ?? product.priceCents;
  return {
    productId: product.id,
    model: product.model,
    name: {
      zh: options.zhName ?? product.name.zh,
      en: options.enName ?? product.name.en,
    },
    partClass,
    qty,
    source: options.source ?? 'web',
    selected: true,
    sellable,
    quoteRequired,
    unitPriceCents,
    subtotalCents: sellable ? unitPriceCents * qty : 0,
    currency: product.currency,
  };
}

function cartItem(
  productId: string,
  qty: number,
  source: CartSource = 'os',
  partClass?: PartClass,
): CartItem {
  const product = getProductById(productId);
  if (!product) throw new Error(`Unknown product id: ${productId}`);
  const resolvedPartClass = partClass ?? product.partClass;
  const quoteRequired = resolvedPartClass !== 'standard' || product.priceCents <= 0;
  return {
    productId,
    qty,
    partClass: resolvedPartClass,
    source,
    selected: true,
    sellable: !quoteRequired,
    quoteRequired,
    syncStatus: 'synced',
    addedAt: Date.parse('2026-06-01T00:00:00.000Z'),
  };
}

